#include "calc.h"

/**
* op_add - calculate the sum of two integers
* @a: first integer
* @b: second integers
*
* Return: sum of a and b
*/
int op_add(int a, int b)
{
	return (a + b);
}

/**
* op_sub - calculate the difference of two integers
* @a: first integer
* @b: second integer
*
* Return: difference of a and b
*/

int op_sub(int a, int b)
{
	return (a - b);
}

/**
* op_mul - calculate the product of two integers
* @a: first integer
* @b: second integers
*
* Return: product of a and b
*/

int op_mul(int a, int b)
{
	return (a * b);
}


/**
* op_div - calculate the division of two integers
* @a: first integer
* @b: second integer
*
* Return: result of division of a by b
*/

int op_div(int a, int b)
{
	return (a / b);
}


/**
* op_mod - calculate the reminder of division of teo integers
* @a: first integers
* @b: second integers
*
* Return: reminder of division of a by b
*/

int op_mod(int a, int b)
{
	return (a % b);
}
